import assert from 'node:assert/strict';
import {TOOL_SLOTS,SAMPLE_SLOTS,STACK_SIZE,usedSlots,sampleRoom,sampleStacks,transferSamples,transferTool} from '../game/src/inventory-state.js';
assert.equal(TOOL_SLOTS,6);assert.equal(SAMPLE_SLOTS,24);assert.equal(STACK_SIZE,64);
const old={bag:{hematite:8},store:{hematite:7},belt:['pickaxe','builder'],locker:['jug'],held:1};
assert.equal(usedSlots(old.bag),1);assert.deepEqual(sampleStacks({hematite:130}).map(s=>s.count),[64,64,2]);
assert.equal(transferTool(old,'jug',false),true);assert.equal(old.belt.length,3);assert.equal(old.belt[old.held],'jug');
assert.equal(transferTool(old,'pickaxe',true),true);assert.equal(old.belt[old.held],'jug','storing earlier tool preserves held identity');
assert.equal(transferTool(old,'jug',true),true);assert.equal(old.held,-1,'storing held tool leaves empty hands');
assert.equal(transferTool(old,'jug',true),false,'no duplicated tool');
const before=old.bag.hematite+old.store.hematite;
assert.equal(transferSamples(old,'hematite',true,64),8);assert.equal(old.bag.hematite,0);
assert.equal(transferSamples(old,'hematite',false,1),1);assert.equal(old.bag.hematite+old.store.hematite,before);
const full={bag:{hematite:1473,gypsum:1},store:{hematite:100,iron:10}};
assert.equal(usedSlots(full.bag),25);assert.equal(sampleRoom(full.bag,'iron'),0,'old overfilled saves keep items but cannot create new slots');
assert.equal(transferSamples(full,'iron',false),0);assert.equal(full.store.iron,10);
const partial={bag:{hematite:1473},store:{hematite:100,iron:10}};
assert.equal(usedSlots(partial.bag),24);assert.equal(sampleRoom(partial.bag,'hematite'),63);assert.equal(sampleRoom(partial.bag,'iron'),0);
assert.equal(transferSamples(partial,'hematite',false),63);assert.equal(partial.bag.hematite,1536);
assert.equal(transferSamples(partial,'hematite',false),0);assert.equal(partial.store.hematite,37);
assert.equal(transferSamples(partial,'hematite',true,64),64);assert.equal(transferSamples(partial,'iron',false,64),10);
const saved=JSON.parse(JSON.stringify(partial));assert.deepEqual(saved,partial);
for(const bad of [-1,NaN,Infinity,0])assert.equal(transferSamples(saved,'iron',true,bad),0);
assert.equal(transferSamples(saved,'not-a-resource',true,10),0);
assert.ok(usedSlots(saved.bag)<=24);
console.log('PASS: larger capacity, stack boundaries, conservation, partial/full bags, old-save counts, held-tool identity, and invalid transfers.');
